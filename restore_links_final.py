def make_link(text, num_str):
    """Create a markdown link for a problem line."""
    # Clean the number string
    num_clean = num_str.strip().rstrip('.')
    # Check LCP/LCR patterns
    lcp_match = re.match(r'(LCP\d+)', num_clean)
    lcr_match = re.match(r'(LCR\d+)', num_clean)
    if lcp_match:
        key = lcp_match.group(1)
        slug = LCP_LCR_SLUGS.get(key)
        if slug:
            return f'- [ ] [{text}](https://leetcode.cn/problems/{slug}/)\n'
    if lcr_match:
        key = lcr_match.group(1)
        slug = LCP_LCR_SLUGS.get(key)
        if slug:
            return f'- [ ] [{text}](https://leetcode.cn/problems/{slug}/)\n'
    # Regular number
    slug = SLUGS.get(num_clean)
    if slug:
        return f'- [ ] [{text}](https://leetcode.cn/problems/{slug}/)\n'
    return None

